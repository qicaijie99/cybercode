export const MEDIA_PROVIDER_CONNECTION_PREFIX = 'media-provider:'

export const MEDIA_PROVIDER_KINDS = ['image', 'video', 'audio'] as const

export type MediaProviderKind = (typeof MEDIA_PROVIDER_KINDS)[number]
export type MediaProviderLocale = 'en' | 'zh' | 'ja' | 'ko'
export type MediaService =
  | 'image-generation'
  | 'image-edit'
  | 'video-generation'
  | 'speech-to-text'
  | 'text-to-speech'
  | 'music-generation'

export type MediaProviderModel = {
  id: string
  label: string
  service: MediaService
}

export type MediaCredentialField = {
  id: string
  label: string
  placeholder: string
  secret: boolean
  required: boolean
}

export type MediaProviderTestAuth =
  | {
      type: 'bearer'
      fieldId: string
    }
  | {
      type: 'header'
      fieldId: string
      headerName: string
      prefix?: string
    }
  | {
      type: 'basic'
      fieldId: string
    }
  | {
      type: 'none'
    }

export type MediaProviderDefinition = {
  kind: MediaProviderKind
  id: string
  runtimeProviderId: string
  credentialGroupId: string
  names: Record<MediaProviderLocale, string>
  logoProviderId: string
  website: string
  baseUrl: string
  connectionMode: 'api-key' | 'credentials' | 'none' | 'local'
  credentialFields: readonly MediaCredentialField[]
  sharedPresetIds: readonly string[]
  defaultModel: string
  models: readonly MediaProviderModel[]
  chinaPriority: boolean
  source: 'omniroute' | 'cybercode'
  test?: {
    url: string
    method?: 'GET' | 'HEAD'
    auth: MediaProviderTestAuth
  }
}

