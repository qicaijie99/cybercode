export const MEDIA_PROVIDERS: readonly MediaProviderDefinition[] = [
  ...IMAGE_PROVIDERS,
  ...VIDEO_PROVIDERS,
  ...AUDIO_PROVIDERS,
] as const

const MEDIA_PROVIDER_BY_KEY = new Map(
  MEDIA_PROVIDERS.map((provider) => [
    getMediaProviderKey(provider.kind, provider.id),
    provider,
  ]),
)

export function getMediaProvidersByKind(
  kind: MediaProviderKind,
): readonly MediaProviderDefinition[] {
  return MEDIA_PROVIDERS.filter((provider) => provider.kind === kind)
}

export function getMediaProvider(
  kind: MediaProviderKind,
  providerId: string,
): MediaProviderDefinition | undefined {
  return MEDIA_PROVIDER_BY_KEY.get(getMediaProviderKey(kind, providerId))
}

export function getMediaProviderKey(
  kind: MediaProviderKind,
  providerId: string,
): string {
  return `${kind}:${providerId}`
}

export function isMediaProviderKind(value: string): value is MediaProviderKind {
  return MEDIA_PROVIDER_KINDS.includes(value as MediaProviderKind)
}

export function getMediaProviderName(
  provider: MediaProviderDefinition,
  locale: string,
): string {
  const normalized = locale === 'zh-CN' ? 'zh' : locale.split('-')[0]
  return provider.names[normalized as MediaProviderLocale] ?? provider.names.en
}
