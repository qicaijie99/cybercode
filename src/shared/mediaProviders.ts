function names(
  en: string,
  zh: string,
  ja: string = en,
  ko: string = en,
): Record<MediaProviderLocale, string> {
  return { en, zh, ja, ko }
}

function models(
  service: MediaService,
  ...items: Array<[string, string]>
): readonly MediaProviderModel[] {
  return items.map(([id, label]) => ({ id, label, service }))
}

function mixedModels(
  ...items: Array<[string, string, MediaService]>
): readonly MediaProviderModel[] {
  return items.map(([id, label, service]) => ({ id, label, service }))
}

